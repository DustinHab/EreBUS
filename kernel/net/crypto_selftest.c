/*
 * crypto_selftest.c -- the seal proves itself before it is trusted.
 *
 * Every primitive is checked against a vector published by the body
 * that standardised it: FIPS for the hash, RFC 4231 for HMAC, RFC 7748
 * for the curve, the NIST GCM suite for the cipher. If any one fails,
 * TLS does not come up at all -- a channel that cannot demonstrate its
 * own arithmetic is not a secure channel, it is a hope.
 */
#include <eb/crypto.h>
#include <eb/fmt.h>
#include <eb/io.h>

static bool eq(const u8 *a, const u8 *b, u32 n)
{
    for (u32 i = 0; i < n; i++) if (a[i] != b[i]) return false;
    return true;
}

bool crypto_selftest(void)
{
    /* SHA-256("abc") */
    {
        u8 out[32];
        static const u8 want[32] = {
            0xba,0x78,0x16,0xbf,0x8f,0x01,0xcf,0xea,0x41,0x41,0x40,0xde,
            0x5d,0xae,0x22,0x23,0xb0,0x03,0x61,0xa3,0x96,0x17,0x7a,0x9c,
            0xb4,0x10,0xff,0x61,0xf2,0x00,0x15,0xad };
        sha256("abc", 3, out);
        if (!eq(out, want, 32)) { kprintf("crypto: sha256 vector failed\n"); return false; }
    }

    /* HMAC-SHA256, RFC 4231 case 1. */
    {
        u8 key[20];
        for (u32 i = 0; i < 20; i++) key[i] = 0x0b;
        u8 out[32];
        static const u8 want[32] = {
            0xb0,0x34,0x4c,0x61,0xd8,0xdb,0x38,0x53,0x5c,0xa8,0xaf,0xce,
            0xaf,0x0b,0xf1,0x2b,0x88,0x1d,0xc2,0x00,0xc9,0x83,0x3d,0xa7,
            0x26,0xe9,0x37,0x6c,0x2e,0x32,0xcf,0xf7 };
        hmac_sha256(key, 20, "Hi There", 8, out);
        if (!eq(out, want, 32)) { kprintf("crypto: hmac vector failed\n"); return false; }
    }

    /* X25519, RFC 7748 section 5.2 first vector. */
    {
        static const u8 scalar[32] = {
            0xa5,0x46,0xe3,0x6b,0xf0,0x52,0x7c,0x9d,0x3b,0x16,0x15,0x4b,
            0x82,0x46,0x5e,0xdd,0x62,0x14,0x4c,0x0a,0xc1,0xfc,0x5a,0x18,
            0x50,0x6a,0x22,0x44,0xba,0x44,0x9a,0xc4 };
        static const u8 point[32] = {
            0xe6,0xdb,0x68,0x67,0x58,0x30,0x30,0xdb,0x35,0x94,0xc1,0xa4,
            0x24,0xb1,0x5f,0x7c,0x72,0x66,0x24,0xec,0x26,0xb3,0x35,0x3b,
            0x10,0xa9,0x03,0xa6,0xd0,0xab,0x1c,0x4c };
        static const u8 want[32] = {
            0xc3,0xda,0x55,0x37,0x9d,0xe9,0xc6,0x90,0x8e,0x94,0xea,0x4d,
            0xf2,0x8d,0x08,0x4f,0x32,0xec,0xcf,0x03,0x49,0x1c,0x71,0xf7,
            0x54,0xb4,0x07,0x55,0x77,0xa2,0x85,0x52 };
        u8 out[32];
        x25519(out, scalar, point);
        if (!eq(out, want, 32)) { kprintf("crypto: x25519 vector failed\n"); return false; }
    }

    /* AES-128-GCM, a NIST CAVS vector with authenticated data and no
     * plaintext: this drives the ghash over real bytes and a length
     * block, the part the empty and single-block cases leave untested. */
    {
        static const u8 key[16] = {
            0x77,0xbe,0x63,0x70,0x89,0x71,0xc4,0xe2,
            0x40,0xd1,0xcb,0x79,0xe8,0xd7,0x7f,0xeb };
        static const u8 iv[12] = {
            0xe0,0xe0,0x0f,0x19,0xfe,0xd7,0xba,0x01,0x36,0xa7,0x97,0xf3 };
        static const u8 aad[16] = {
            0x7a,0x43,0xec,0x1d,0x9c,0x0a,0x5a,0x78,
            0xa0,0xb1,0x65,0x33,0xa6,0x21,0x3c,0xab };
        static const u8 want_tag[16] = {
            0x20,0x9f,0xcc,0x8d,0x36,0x75,0xed,0x93,
            0x8e,0x9c,0x71,0x66,0x70,0x9d,0xd9,0x46 };
        u8 tag[16];
        aes128_gcm_seal(key, iv, aad, 16, 0, 0, 0, tag);
        for (u32 i = 0; i < 16; i++)
            if (tag[i] != want_tag[i]) {
                kprintf("crypto: gcm-aad tag[%u] got %02x want %02x\n",
                        i, tag[i], want_tag[i]);
                return false;
            }
    }

    /* AES-128-GCM, NIST case 1: no data at all, so the tag is purely
     * the mask AES(J0) -- this isolates the cipher from the ghash. */
    {
        u8 key[16] = { 0 }, iv[12] = { 0 };
        u8 tag[16];
        static const u8 want_tag[16] = {
            0x58,0xe2,0xfc,0xce,0xfa,0x7e,0x30,0x61,
            0x36,0x7f,0x1d,0x57,0xa4,0xe7,0x45,0x5a };
        aes128_gcm_seal(key, iv, 0, 0, 0, 0, 0, tag);
        for (u32 i = 0; i < 16; i++)
            if (tag[i] != want_tag[i]) {
                kprintf("crypto: gcm-empty tag[%u] got %02x want %02x\n",
                        i, tag[i], want_tag[i]);
                return false;
            }
    }

    /* X25519, RFC 7748 second vector, to exercise the curve on a
     * different point than the first. */
    {
        static const u8 scalar[32] = {
            0x4b,0x66,0xe9,0xd4,0xd1,0xb4,0x67,0x3c,0x5a,0xd2,0x26,0x91,
            0x95,0x7d,0x6a,0xf5,0xc1,0x1b,0x64,0x21,0xe0,0xea,0x01,0xd4,
            0x2c,0xa4,0x16,0x9e,0x79,0x18,0xba,0x0d };
        static const u8 point[32] = {
            0xe5,0x21,0x0f,0x12,0x78,0x68,0x11,0xd3,0xf4,0xb7,0x95,0x9d,
            0x05,0x38,0xae,0x2c,0x31,0xdb,0xe7,0x10,0x6f,0xc0,0x3c,0x3e,
            0xfc,0x4c,0xd5,0x49,0xc7,0x15,0xa4,0x93 };
        static const u8 want[32] = {
            0x95,0xcb,0xde,0x94,0x76,0xe8,0x90,0x7d,0x7a,0xad,0xe4,0x5c,
            0xb4,0xb8,0x73,0xf8,0x8b,0x59,0x5a,0x68,0x79,0x9f,0xa1,0x52,
            0xe6,0xf8,0xf7,0x64,0x7a,0xac,0x79,0x57 };
        u8 out[32];
        x25519(out, scalar, point);
        if (!eq(out, want, 32)) { kprintf("crypto: x25519 vector 2 failed\n"); return false; }
    }

    /* AES-128-GCM, the classic multi-block vector with aad: 60 bytes
     * of plaintext over four-and-a-bit blocks, which the single-block
     * cases never exercise. */
    {
        static const u8 key[16] = {
            0xfe,0xff,0xe9,0x92,0x86,0x65,0x73,0x1c,
            0x6d,0x6a,0x8f,0x94,0x67,0x30,0x83,0x08 };
        static const u8 iv[12] = {
            0xca,0xfe,0xba,0xbe,0xfa,0xce,0xdb,0xad,0xde,0xca,0xf8,0x88 };
        static const u8 aad[20] = {
            0xfe,0xed,0xfa,0xce,0xde,0xad,0xbe,0xef,0xfe,0xed,
            0xfa,0xce,0xde,0xad,0xbe,0xef,0xab,0xad,0xda,0xd2 };
        static const u8 pt[60] = {
            0xd9,0x31,0x32,0x25,0xf8,0x84,0x06,0xe5,0xa5,0x59,0x09,0xc5,
            0xaf,0xf5,0x26,0x9a,0x86,0xa7,0xa9,0x53,0x15,0x34,0xf7,0xda,
            0x2e,0x4c,0x30,0x3d,0x8a,0x31,0x8a,0x72,0x1c,0x3c,0x0c,0x95,
            0x95,0x68,0x09,0x53,0x2f,0xcf,0x0e,0x24,0x49,0xa6,0xb5,0x25,
            0xb1,0x6a,0xed,0xf5,0xaa,0x0d,0xe6,0x57,0xba,0x63,0x7b,0x39 };
        static const u8 want_ct[60] = {
            0x42,0x83,0x1e,0xc2,0x21,0x77,0x74,0x24,0x4b,0x72,0x21,0xb7,
            0x84,0xd0,0xd4,0x9c,0xe3,0xaa,0x21,0x2f,0x2c,0x02,0xa4,0xe0,
            0x35,0xc1,0x7e,0x23,0x29,0xac,0xa1,0x2e,0x21,0xd5,0x14,0xb2,
            0x54,0x66,0x93,0x1c,0x7d,0x8f,0x6a,0x5a,0xac,0x84,0xaa,0x05,
            0x1b,0xa3,0x0b,0x39,0x6a,0x0a,0xac,0x97,0x3d,0x58,0xe0,0x91 };
        static const u8 want_tag[16] = {
            0x5b,0xc9,0x4f,0xbc,0x32,0x21,0xa5,0xdb,
            0x94,0xfa,0xe9,0x5a,0xe7,0x12,0x1a,0x47 };
        u8 ct[60], tag[16];
        aes128_gcm_seal(key, iv, aad, 20, pt, 60, ct, tag);
        if (!eq(ct, want_ct, 60)) {
            for (u32 i = 0; i < 60; i++)
                if (ct[i] != want_ct[i]) {
                    kprintf("crypto: gcm-multi ct[%u] got %02x want %02x\n",
                            i, ct[i], want_ct[i]);
                    break;
                }
            return false;
        }
        if (!eq(tag, want_tag, 16)) {
            kprintf("crypto: gcm-multi tag mismatch\n");
            return false;
        }
    }

    /* AES-128-GCM, NIST test case for a keystreamed block: the
     * ciphertext is a published value; the tag is checked by sealing
     * and opening, which must return the plaintext and refuse a forged
     * tag. The two vectors above already pin the tag arithmetic. */
    {
        u8 key[16] = { 0 }, iv[12] = { 0 };
        u8 pt[16] = { 0 }, ct[16], tag[16];
        static const u8 want_ct[16] = {
            0x03,0x88,0xda,0xce,0x60,0xb6,0xa3,0x92,
            0xf3,0x28,0xc2,0xb9,0x71,0xb2,0xfe,0x78 };
        aes128_gcm_seal(key, iv, 0, 0, pt, 16, ct, tag);
        if (!eq(ct, want_ct, 16)) {
            kprintf("crypto: aes-gcm ct vector failed\n");
            return false;
        }

        u8 back[16];
        if (!aes128_gcm_open(key, iv, 0, 0, ct, 16, tag, back) ||
            !eq(back, pt, 16)) {
            kprintf("crypto: aes-gcm open failed\n");
            return false;
        }
        u8 bad[16];
        for (u32 i = 0; i < 16; i++) bad[i] = tag[i];
        bad[0] ^= 1;
        if (aes128_gcm_open(key, iv, 0, 0, ct, 16, bad, back)) {
            kprintf("crypto: aes-gcm accepted a forged tag\n");
            return false;
        }
    }

    return true;
}
